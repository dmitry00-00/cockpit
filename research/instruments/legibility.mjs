// И5: сколько CSS-пикселей нужно, чтобы деталь читалась с расстояния стола. Геометрия, не замер глаз:
//   размер = расстояние · tg(угол); CSS px → мм по ширине панели и ширине экрана в CSS px.
// Пороги:
//   текст  — высота прописной 16′ (нижний предел) и 20′ (рекомендуемый) — ISO 9241-303 для чтения;
//            кегль = высота прописной / 0,7 (у PT Sans, Plex Mono и Forum прописная около 0,65–0,70 em);
//   черта  — толщина 2′ (вдвое выше предела остроты 1′ — видна, а не угадывается);
//   форма  — предмет 60′ (1°): уровень шара, фаза луны, угол стрелки читаются без чисел.
//   node research/instruments/legibility.mjs
const SCREENS = [
  ['MacBook Air 13,6″ (1470 px «как будто»)', 290, 1470],
  ['MacBook Pro 14″ (1512 px)', 302, 1512],
  ['Windows 15,6″ FHD, масштаб 125 %', 344, 1536],
  ['Windows 14″ FHD, масштаб 150 %', 310, 1280],
  ['Монитор 24″ FHD, 100 %', 531, 1920],
  ['Телевизор 55″ FHD, 100 %', 1210, 1920],
];
const DIST = [600, 1000, 1500, 2000, 3000];
const mm = (d, arcmin) => d * Math.tan((arcmin / 60) * (Math.PI / 180));
const rows = [];
for (const [name, wmm, wpx] of SCREENS) {
  const pxmm = wmm / wpx;
  for (const d of DIST) {
    const px = a => mm(d, a) / pxmm;
    rows.push({ экран: name, 'мм на CSS px': +pxmm.toFixed(3), 'расстояние, м': d / 1000, 'кегль 16′': Math.ceil(px(16) / 0.7), 'кегль 20′': Math.ceil(px(20) / 0.7), 'черта 2′': +px(2).toFixed(1), 'форма 1°': Math.ceil(px(60)) });
  }
}
console.table(rows);
// Что видно у прототипа: сторона 400 px, подписи месяцев 15 px, цифры лимба 14 px, время на плите 24 px, шар 120 px.
const angle = (sizePx, pxmm, d) => (Math.atan((sizePx * pxmm) / d) * 180 * 60) / Math.PI; // угловые минуты
const P = [['прибор 400 px', 400], ['кольцо года 34 px', 34], ['прописная подписи месяца 15 px', 15 * 0.65], ['прописная цифры лимба 14 px', 14 * 0.7], ['прописная времени 24 px', 24 * 0.7], ['шар хитов 120 px', 120], ['деление лимба 2 px', 2], ['кегль 13 px (минимум стола)', 13 * 0.7], ['кегль 8 px (type-num-12)', 8 * 0.7]];
const out = [];
for (const [what, s] of P) {
  const r = { что: what };
  for (const d of [600, 1000, 2000]) r[`MacBook 14″, ${d / 1000} м, ′`] = +angle(s, 302 / 1512, d).toFixed(1);
  r['Win 15,6″ 125 %, 2 м, ′'] = +angle(s, 344 / 1536, 2000).toFixed(1);
  out.push(r);
}
console.table(out);
