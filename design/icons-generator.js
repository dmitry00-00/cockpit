// Генератор иконок DM Cockpit. Сетка 16×16, четыре тона.
// Форма собирается из примитивов; фаска считается автоматически — свет сверху-слева.
// Один генератор на весь набор: новая иконка — это 3–6 строк формы, а не сетка руками.
const N = 16;

const disc = (cx, cy, r) => (x, y) => (x + .5 - cx) ** 2 + (y + .5 - cy) ** 2 <= r * r;
const ell = (cx, cy, rx, ry) => (x, y) => ((x + .5 - cx) / rx) ** 2 + ((y + .5 - cy) / ry) ** 2 <= 1;
const rect = (x0, y0, w, h) => (x, y) => x >= x0 && x < x0 + w && y >= y0 && y < y0 + h;
const poly = pts => (x, y) => {
  const px = x + .5, py = y + .5; let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i], [xj, yj] = pts[j];
    if ((yi > py) !== (yj > py) && px < (xj - xi) * (py - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const seg = (x0, y0, x1, y1, w) => (x, y) => {
  const px = x + .5, py = y + .5, dx = x1 - x0, dy = y1 - y0;
  const t = Math.max(0, Math.min(1, ((px - x0) * dx + (py - y0) * dy) / (dx * dx + dy * dy || 1)));
  return (px - (x0 + t * dx)) ** 2 + (py - (y0 + t * dy)) ** 2 <= (w / 2) ** 2;
};
const not2 = (a, b) => (x, y) => a(x, y) && !b(x, y);
const above = (f, y0) => (x, y) => f(x, y) && y < y0;
const below = (f, y0) => (x, y) => f(x, y) && y >= y0;
const ring = (cx, cy, r, w) => not2(disc(cx, cy, r), disc(cx, cy, r - w));
const ering = (cx, cy, rx, ry, w) => not2(ell(cx, cy, rx, ry), ell(cx, cy, rx - w, ry - w));

function build(ops) {
  const m = Array.from({ length: N }, () => Array(N).fill(0));
  for (const [kind, f] of ops)
    for (let y = 0; y < N; y++) for (let x = 0; x < N; x++)
      if (f(x, y)) m[y][x] = kind === '-' ? 0 : 1;
  return m;
}
function shade(m) {
  let sx = 0, sy = 0, n = 0;
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) if (m[y][x]) { sx += x; sy += y; n++; }
  const cx = sx / (n || 1), cy = sy / (n || 1);
  const at = (x, y) => (x < 0 || y < 0 || x >= N || y >= N) ? 0 : m[y][x];
  const out = [];
  for (let y = 0; y < N; y++) {
    let row = '';
    for (let x = 0; x < N; x++) {
      if (!m[y][x]) { row += '0'; continue; }
      const up = at(x, y - 1), left = at(x - 1, y), down = at(x, y + 1), right = at(x + 1, y);
      let t;
      if (!up || !left) t = 4;
      else if (!down || !right) t = 1;
      else t = ((x - cx) + (y - cy) < -0.5) ? 3 : 2;
      row += t;
    }
    out.push(row);
  }
  return out.join('/');
}

